import Dexie, { type Table } from 'dexie';
import type {
  ClassRoom,
  Student,
  AttendanceRecord,
  LessonExtract,
  OfficialLetter,
  YearlyPlanItem,
  StudentGrade,
  TimetableSlot,
  TeacherSettings,
  TeachingPlan,
} from '../types';
import {
  initialClasses,
  initialStudents,
  initialAttendance,
  initialExtracts,
  initialYearlyPlan,
  initialSettings,
  initialTimetable,
} from './seedData';

import { enrichStudentWithMoEYSFields } from '../utils/studentEnricher';
import { getStreamForClass, parseGradeNumber } from '../utils/classUtils';
